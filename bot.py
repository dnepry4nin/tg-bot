@bot.message_handler(content_types=['text'])
def handle_buttons(message):
    chat_id = message.chat.id
    if message.text == '📸 Письмо':
        with open('photo.jpg', 'rb') as photo:
            bot.send_photo(chat_id, photo, caption='это точно останется в твоей голове надолго)')
    elif message.text == '🎥Видосик':
        with open('video.mp4', 'rb') as video:
            bot.send_document(chat_id, video, caption='этот момент столь же прекрасен, как твой день рождения, дорогая ☺️')
    elif message.text == '✨ Загадать желание':
        markup_inline = types.InlineKeyboardMarkup()
        btn_blow = types.InlineKeyboardButton('🕯️ Задуть свечи и загадать', callback_data='blow_candles')
        markup_inline.add(btn_blow)
        bot.send_message(chat_id, "🎂 Загадай самое сокровенное желание...\n\nКогда будешь готова, нажми на кнопку ниже:", reply_markup=markup_inline)
    elif message.text == '🎵музыка для вайба':
        bot.send_message(chat_id, "тут треки, которые ассоциируются с тобой или просто подходят по вайбу, наслаждайся 😌\n\nhttps://on.soundcloud.com/NKq3RvWLvlMFe8pmku")
    elif message.text == '🔮 Гороскоп на 18 лет':
        if chat_id not in user_horoscopes or not user_horoscopes[chat_id]:
            user_horoscopes[chat_id] = MASTER_HOROSCOPES.copy()
